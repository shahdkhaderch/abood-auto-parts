// Generates lib/product-images.generated.ts: a map of product code -> photo path,
// built from the files in public/products. Runs automatically before dev/build/lint.
// Matching is case-insensitive, so "bg2j0019.JPG" still matches code "BG2J0019".

import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, extname, basename } from "node:path";

const root = process.cwd();
const dir = join(root, "public", "products");
const out = join(root, "lib", "product-images.generated.ts");
const exts = new Set([".jpg", ".jpeg", ".png", ".webp"]);

const map = {};
if (existsSync(dir)) {
  for (const file of readdirSync(dir).sort()) {
    const ext = extname(file).toLowerCase();
    if (!exts.has(ext)) continue;
    const key = basename(file, extname(file)).trim().toLowerCase();
    // Prefer .jpg if several formats exist for the same code.
    if (map[key] && extname(map[key]).toLowerCase() === ".jpg") continue;
    map[key] = `/products/${file}`;
  }
}

const body =
  "// AUTO-GENERATED by scripts/gen-product-images.mjs. Do not edit.\n" +
  "// Keys are product slugs (lowercase codes); values are paths under /public.\n" +
  `export const PRODUCT_IMAGES: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;

writeFileSync(out, body);
console.log(`[product-images] ${Object.keys(map).length} photo(s) found in public/products`);
